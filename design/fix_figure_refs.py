# ── 解説・誤答解説から図表番号を消す ───────────────────
EXPL_SUB = [
    (r"表\s?\d+[-–]\d+\s?[「『][^」』]*[」』](では|には|の)", "マニュアルでは"),
    (r"(図|表)\s?\d+[-–]\d+(では|には|に|の項目には|より)", "マニュアルでは"),
    (r"同じ表で", "同じ一覧で"),
    (r"(図|表)\s?\d+[-–]\d+\s?", ""),
    (r"『[^』]*』を参照するよう案内されている。?", ""),
]


def apply_subs(text, subs):
    for pat, rep in subs:
        text = re.sub(pat, rep, text)
    return re.sub(r"\s{2,}", " ", text).strip()


def main():
    path = os.path.join(RES, "questions.json")
    qs = json.load(open(path, encoding="utf-8"))
    rewritten = stems = symbols = expls = 0

    for q in qs:
        r = REWRITE.get(q["id"])
        if r:
            q.update(r)
            rewritten += 1
            continue

        before = q["question"]
        q["question"] = apply_subs(q["question"], STEM_SUB)
        if q["question"] != before:
            stems += 1

        for old, new in CHOICE_SUB:
            if any(old in c for c in q["choices"]):
                q["choices"] = [c.replace(old, new) for c in q["choices"]]

        hit = False
        for old, new in SYMBOL_SUB:
            if any(old in c for c in q["choices"]) or old in q["explanation"]:
                q["choices"] = [c.replace(old, new) for c in q["choices"]]
                q["explanation"] = q["explanation"].replace(old, new)
                q["wrongChoiceExplanations"] = {
                    k: v.replace(old, new) for k, v in (q.get("wrongChoiceExplanations") or {}).items()}
                hit = True
        if hit:
            symbols += 1

        eb = q["explanation"]
        q["explanation"] = apply_subs(q["explanation"], EXPL_SUB)
        we = q.get("wrongChoiceExplanations") or {}
        q["wrongChoiceExplanations"] = {k: apply_subs(v, EXPL_SUB) for k, v in we.items()}
        if q["explanation"] != eb:
            expls += 1

    print(f"作り直した問題           : {rewritten}問")
    print(f"設問から表番号を外した   : {stems}問")
    print(f"○△－を言葉に置き換えた  : {symbols}問")
    print(f"解説から図表番号を外した : {expls}問")

    # 残りを検査
    left_q = [q["id"] for q in qs if re.search(r"(図|表)\s?\d+[-–]\d+", q["question"])]
    left_c = [q["id"] for q in qs if any(re.search(r"(図|表)\s?\d+[-–]\d+", c) for c in q["choices"])]
    left_e = [q["id"] for q in qs if re.search(r"(図|表)\s?\d+[-–]\d+", q["explanation"])]
    print(f"\n残存：設問 {len(left_q)} / 選択肢 {len(left_c)} / 解説 {len(left_e)}")
    for ids in (left_q, left_c, left_e):
        if ids:
            print("   ", ids[:8])

    if DRY:
        print("\n(--dry のため書き込みなし)")
        return
    json.dump(qs, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("\n書き込み完了")


if __name__ == "__main__":
    main()
