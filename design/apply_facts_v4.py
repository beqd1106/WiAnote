fix_map = {f["id"]: f for f in FIXES}
applied = set()

for path in sorted(glob.glob(os.path.join(DESIGN, "batch_*.json"))) + \
            sorted(glob.glob(os.path.join(DESIGN, "drill_*.json"))):
    data = json.load(open(path, encoding="utf-8"))
    changed = False
    for q in data:
        f = fix_map.get(q["id"])
        if not f:
            continue
        for k, v in f.items():
            if k == "id":
                continue
            q[k] = v
        applied.add(q["id"]); changed = True
    if changed:
        json.dump(data, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print("updated", os.path.basename(path))

missing = set(fix_map) - applied
if missing:
    raise SystemExit(f"対象idが見つかりません: {sorted(missing)}")

