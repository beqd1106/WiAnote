for path in sorted(glob.glob(os.path.join(DESIGN, "fix_choices*.json"))):
    data = json.load(open(path, encoding="utf-8"))
    kept = [d for d in data if d["id"] not in applied]
    if len(kept) != len(data):
        json.dump(kept, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print(f"{os.path.basename(path)}: {len(data)} -> {len(kept)}")

